"""
Lists everything that must be resolved before submission and writes CHECKLIST.md:
  1. \fillin{...} placeholders in main.tex (PRISMA counts, dates, authors, links)
  2. [VERIFY] notes in references.bib and \verify marks in main.tex
  3. Section V: every example is a mapped full-text study, and Section V cites nothing outside the map
     except the methodology and taxonomy sources listed in SEC5_ALLOWED
  4. PRISMA counts still None in figures/fig1_prisma.py
Run:  python tools/check_submission.py
"""
import csv, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tex = open(os.path.join(ROOT, "main.tex"), encoding="utf-8").read()
tex_nc = "\n".join(l.split("%")[0] if not l.lstrip().startswith("%") else "" for l in tex.splitlines())
bib = open(os.path.join(ROOT, "references.bib"), encoding="utf-8").read()
ex = list(csv.DictReader(open(os.path.join(ROOT, "data", "section5_examples.csv"), encoding="utf-8")))
mapped = {r["key"]: r for r in csv.DictReader(open(os.path.join(ROOT, "data", "mapped_studies.csv"), encoding="utf-8"))}
SEC5_ALLOWED = {"yang2016survey"}   # source of the embedded/ranked distinction (Section V-A)
# Sections VI-VIII may also cite background sources that are not hybrid planning studies:
# environment representations, obstacle-motion models and predictors, benchmarks and simulators, and domain reviews.
BACKGROUND = {"elfes1989using", "lu2014layered", "hornung2013octomap", "oleynikova2017voxblox", "rosinol2020kimera",
              "hughes2022hydra", "kalman1960new", "zhu2019chance", "fiorini1998motion", "vandenberg2011reciprocal",
              "alahi2016social", "gupta2018social", "salzmann2020trajectron", "rudenko2020human", "phillips2011sipp",
              "trautman2010unfreezing", "xiao2022autonomous", "sturtevant2012benchmarks", "stern2019multi",
              "moll2015benchmarking", "heiden2021benchmr", "perille2020benchmarking", "kastner2022arenabench",
              "althoff2017commonroad", "caesar2021nuplan", "dosovitskiy2017carla", "koenig2004design",
              "panda2020comprehensive", "aggarwal2020path",
              "patle2019review", "sanchezibanez2021path", "qin2023review", "shanmugaraja2025hybrid"}   # earlier reviews (Sec. VIII-E)
MAPPED_EXTRA = {"samavi2025sicnav": "R13523"}   # mapped studies cited outside the Section V example set
prisma = open(os.path.join(ROOT, "figures", "fig1_prisma.py"), encoding="utf-8").read()

out = ["# Pre-submission checklist", "",
       "Auto-generated by `tools/check_submission.py`. Re-run after every edit.", ""]

# 1. fill-ins
macros = re.findall(r"\\newcommand\{(\\[A-Za-z]+)\}\{\\fillin\{", tex_nc)
inline = [m for m in re.findall(r"\\fillin\{([^{}]*(?:\{[^{}]*\}[^{}]*)*)\}", tex_nc)
          if not m.startswith("$")]
out += [f"## 1. Placeholders in main.tex ({len(macros)} macros, {len(inline)} inline)", "",
        "PRISMA and screening macros (define once at the top of main.tex):", ""]
out += [f"- [ ] `{name}`" for name in macros]
out += ["", "Inline placeholders:", ""] + [f"- [ ] {m}" for m in sorted(set(inline))]
nverify_tex = len(re.findall(r"\\verify\b", tex_nc)) - 1   # minus the definition
out += ["", f"`\\verify` marks in the text: {nverify_tex} (prior-review coverage judgments in Table I).", ""]

# 2. bibliography
entries = re.findall(r"@\w+\{([^,]+),(.*?)\n\}", bib, re.S)
flag = [(k, re.search(r"note\s*=\s*\{\[VERIFY\]\s*([^}]*)\}", body).group(1).strip())
        for k, body in entries if "[VERIFY]" in body]
nodoi = [k for k, body in entries if "doi" not in body and "howpublished" not in body]
out += [f"## 2. Bibliography ({len(entries)} entries)", "",
        f"Entries flagged [VERIFY]: {len(flag)}", ""]
out += [f"- [ ] `{k}`: {what}" for k, what in flag]
out += ["", f"Entries without a DOI (check whether one exists; books, AAAI/NeurIPS/PMLR papers often have none): {len(nodoi)}", ""]
out += [f"- [ ] `{k}`" for k in nodoi]
out += ["", "Remove every `note = {[VERIFY] ...}` field once checked, or it will print in the reference list.", ""]

# 3. Section V
bad_ex = [r["bibkey"] for r in ex if r["record_id"] not in mapped or mapped[r["record_id"]]["basis"] != "FT"]
sec5 = tex_nc[tex_nc.index(r"\section{Hybrid Path Planning}"):tex_nc.index(r"\section{Dynamic Environment Modeling}")]
for f in ("tables/examples_table.tex",):
    sec5 += open(os.path.join(ROOT, f), encoding="utf-8").read()
cited5 = {k.strip() for m in re.findall(r"\\cite\{([^}]*)\}", sec5) for k in m.split(",")}
outside = sorted(cited5 - {r["bibkey"] for r in ex} - SEC5_ALLOWED)
out += [f"## 3. Section V ({len(ex)} example studies, {len(cited5)} keys cited)", "",
        f"- [{'x' if not bad_ex else ' '}] Every example is a mapped full-text study" + (f": not met for {', '.join(bad_ex)}" if bad_ex else ""),
        f"- [{'x' if not outside else ' '}] Section V cites no study outside the map" + (f": {', '.join(outside)}" if outside else ""), ""]
bad_extra = [k for k, rid in MAPPED_EXTRA.items() if rid not in mapped]
sec68 = tex_nc[tex_nc.index(r"\section{Dynamic Environment Modeling}"):tex_nc.index(r"\section{Open Challenges and Future Directions}")]
cited68 = {k.strip() for m in re.findall(r"\\cite\{([^}]*)\}", sec68) for k in m.split(",")}
outside68 = sorted(cited68 - {r["bibkey"] for r in ex} - set(MAPPED_EXTRA) - BACKGROUND)
out += [f"- [{'x' if not (outside68 or bad_extra) else ' '}] Sections VI-VIII cite only mapped studies and listed background sources"
        + (f": {', '.join(outside68 + bad_extra)}" if (outside68 or bad_extra) else ""), ""]

# 4. PRISMA script
nnone = len(re.findall(r":\s*None", prisma.split("# 2. Derived")[0]))
out += ["## 4. PRISMA flow diagram", "",
        f"- [ ] {nnone} counts in `figures/fig1_prisma.py` are still `None` (shown as 'n = ?').", ""]

# 5. manual items
out += ["## 5. Manual checks", "",
        "- [ ] Replace the placeholder author block, affiliations, and journal header.",
        "- [ ] Read Shanmugaraja et al. (2025) and confirm the differentiation claimed in Section I-B.",
        "- [ ] Check the body length against the journal limit (see build_all.py output).",
        "- [ ] Compile with the journal's own IEEEtran class and check float placement.", ""]

open(os.path.join(ROOT, "CHECKLIST.md"), "w", encoding="utf-8").write("\n".join(out))
print(f"CHECKLIST.md written: {len(macros)} macros, {len(set(inline))} inline placeholders, "
      f"{len(flag)} [VERIFY] bib entries, {len(nodoi)} without DOI; Section V outside-map citations: {len(outside)}.")
